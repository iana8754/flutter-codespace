class City {
  final String name;
  final String? region;
  final double lat, lon;
  final bool isGps;

  const City({
    required this.name,
    this.region,
    required this.lat,
    required this.lon,
    this.isGps = false,
  });

  bool sameAs(City o) => (lat - o.lat).abs() < 0.05 && (lon - o.lon).abs() < 0.05;

  Map<String, dynamic> toJson() =>
      {'name': name, 'region': region, 'lat': lat, 'lon': lon};

  factory City.fromJson(Map<String, dynamic> j) => City(
        name: j['name'] as String,
        region: j['region'] as String?,
        lat: (j['lat'] as num).toDouble(),
        lon: (j['lon'] as num).toDouble(),
      );
}

City cityFromRecord((String, String, double, double) r) =>
    City(name: r.$1, region: r.$2, lat: r.$3, lon: r.$4);

